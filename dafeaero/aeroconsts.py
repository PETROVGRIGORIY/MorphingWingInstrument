"""Аэродинамические константы в СИ, индекс 0 - уровень моря по ISA."""
from math import sqrt

__all__ = ["g", "p0", "T0", "R_air", "gamma_air", "rho0", "a0", "mu0", "nu0"]

g = 9.80665             # ускорение свободного падения, м/с²
p0 = 101325.0           # давление на уровне моря, Па
T0 = 288.15             # температура на уровне моря, К
R_air = 287.05287       # газовая постоянная воздуха, Дж/(кг·К)
gamma_air = 1.4         # показатель адиабаты воздуха

rho0 = p0 / (R_air * T0)                       # плотность, кг/м³ (≈ 1.225)
a0 = sqrt(gamma_air * R_air * T0)              # скорость звука, м/с (≈ 340.29)
mu0 = 1.458e-6 * T0**1.5 / (T0 + 110.4)        # динамическая вязкость, Па·с (≈ 1.789e-5)
nu0 = mu0 / rho0
